export function normalizeLanguage(language) {
  return SUPPORTED_LANGUAGES.includes(language)
    ? language
    : DEFAULT_LANGUAGE;
}

export function translate(language, key, values = {}) {
  const normalized = normalizeLanguage(language);
  const dictionary = translations[normalized] || translations[DEFAULT_LANGUAGE];
  const fallback = translations[DEFAULT_LANGUAGE][key];
  const template = dictionary[key] ?? fallback ?? key;
  if (typeof template === "function") return template(values);
  return String(template).replace(/\{(\w+)\}/g, (_match, name) =>
    values[name] === undefined ? `{${name}}` : String(values[name]),
  );
}

export function formatLocalizedDate(language, date = new Date()) {
  const normalized = normalizeLanguage(language);
  return new Intl.DateTimeFormat(normalized === "en" ? "en-US" : "zh-CN", {
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    hour12: false,
  }).format(date);
}

export function formatPageCount(language, count) {
  const safeCount = Number(count) || 0;
  return normalizeLanguage(language) === "en"
    ? `${safeCount} ${safeCount === 1 ? "page" : "pages"}`
    : `${safeCount} 页图片`;
}

export function formatItemCount(language, count) {
  const safeCount = Number(count) || 0;
  return normalizeLanguage(language) === "en"
    ? `${safeCount} ${safeCount === 1 ? "item" : "items"}`
    : `${safeCount} 项`;
}

export function formatPageOption(language, index, total) {
  return normalizeLanguage(language) === "en"
    ? `Page ${index} of ${total}`
    : `第 ${index} / ${total} 页`;
}

export function formatOpenErrorCount(language, count) {
  const safeCount = Number(count) || 0;
  return normalizeLanguage(language) === "en"
    ? `${safeCount} ${safeCount === 1 ? "file" : "files"} could not be opened`
    : `${safeCount} 个文件未能打开`;
}

export function formatMultiPageMessage(language, count, compact = false) {
  const safeCount = Number(count) || 0;
  if (normalizeLanguage(language) === "en") {
    return compact
      ? `${safeCount} pages created. Choose one in the window`
      : `${safeCount} pages created. Choose the page to copy`;
  }
  return compact
    ? `内容已拆成 ${safeCount} 页，请在窗口中选择`
    : `内容已拆成 ${safeCount} 页，请选择需要复制的页面`;
}

export function createLocalizedError(language, key, values = {}) {
  const error = new Error(translate(language, key, values));
  error.code = key;
  return error;
}
